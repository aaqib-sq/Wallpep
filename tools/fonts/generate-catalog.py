#!/usr/bin/env python3
"""Generate FontCatalog.kt from the FONTS.md inventory.

Run after tools/fonts/import-fonts.py:

    python3 tools/fonts/generate-catalog.py licenses/fonts/FONTS.md \
        app/src/main/java/dev/wallpep/fonts/FontCatalog.kt

One entry is produced per family (112 currently). The representative face for a
family is the first match of: static Regular, upright variable face, any variable
face, any upright face, any face. The app therefore ships all 185 files while the
picker lists families, the same way a font menu normally behaves.
"""
import sys
from collections import defaultdict
from importlib.machinery import SourceFileLoader
from pathlib import Path

CATEGORY_ORDER = ["sans", "serif", "display", "mono", "handwriting", "decorative"]
HEADER = '''package dev.wallpep.fonts

import android.content.Context
import android.graphics.Typeface
import java.util.Locale

/**
 * Wallpep's own typeface library: {families} families, {files} files, all taken from the
 * Google Fonts repository (github.com/google/fonts, commit {commit}) — the `ofl/` directory
 * plus the five families that live in `apache/`. No font came from any other app.
 *
 * Generated by `tools/fonts/generate-catalog.py` from `licenses/fonts/FONTS.md`; edit the
 * inventory and regenerate rather than editing this table by hand.
 */
enum class FontCategory(val label: String) {{
    SANS("Sans"),
    SERIF("Serif"),
    DISPLAY("Display"),
    MONO("Mono"),
    HANDWRITING("Handwriting"),
    DECORATIVE("Decorative"),
}}

enum class FontLicense(val label: String, val fileName: String) {{
    OFL("SIL OFL 1.1", "OFL.txt"),
    APACHE("Apache-2.0", "LICENSE-Apache-2.0.txt"),
}}

/** [assetPath] is the representative face; [files] counts the styles bundled for the family. */
data class FontFamily(
    val id: String,
    val label: String,
    val category: FontCategory,
    val assetPath: String,
    val license: FontLicense,
    val files: Int,
) {{
    val licenseAssetPath: String get() = assetPath.substringBeforeLast('/') + "/" + license.fileName
    val styleLabel: String get() = if (files == 1) "1 style" else "$files styles"
}}

object FontCatalog {{
    /** Used when nothing is stored yet, and as the safe fallback for unknown values. */
    const val DEFAULT_ID = "outfit"

    /** The device's own sans face; it is not part of the bundled library. */
    const val SYSTEM_ID = "system"

    /** Date picker value that reuses the clock family. */
    const val FOLLOW_CLOCK = "follow-clock"

    private val bundled: List<FontFamily> = listOf(
{rows}
    )

    /** Every family, grouped by category and alphabetical inside a category. */
    val families: List<FontFamily> = bundled.sortedWith(compareBy({{ it.category.ordinal }}, {{ it.label.lowercase(Locale.ROOT) }}))

    private val byId: Map<String, FontFamily> = families.associateBy {{ it.id }}

    fun family(id: String?): FontFamily? = id?.let(byId::get)

    fun assetPath(id: String?): String? = family(id)?.assetPath

    /** The license text shipped beside a family's files, so it travels inside the APK. */
    fun licenseAssetPath(id: String?): String? = family(id)?.licenseAssetPath

    fun displayName(id: String?): String = when (id) {{
        null -> "—"
        SYSTEM_ID -> "System sans"
        FOLLOW_CLOCK -> "Same as clock"
        else -> family(id)?.label ?: family(DEFAULT_ID)?.label.orEmpty()
    }}

    /** Accepts only bundled ids plus the two sentinels; anything else falls back to Outfit. */
    fun sanitizeId(value: String?): String = migrate(value) ?: DEFAULT_ID

    /** The date face may additionally follow the clock face. */
    fun sanitizeDateId(value: String?): String =
        if (value == FOLLOW_CLOCK) FOLLOW_CLOCK else migrate(value) ?: FOLLOW_CLOCK

    /** Phase 1/2 stored enum names (`OUTFIT`, `DM_SANS`, `SYSTEM`) keep working. */
    fun migrate(value: String?): String? {{
        if (value.isNullOrBlank()) return null
        when (value.uppercase(Locale.ROOT)) {{
            "OUTFIT" -> return "outfit"
            "DM_SANS" -> return "dmsans"
            "SYSTEM" -> return SYSTEM_ID
        }}
        val candidate = value.trim().lowercase(Locale.ROOT).replace("-", "").replace("_", "")
        return candidate.takeIf {{ it == SYSTEM_ID || byId.containsKey(it) }}
    }}

    fun search(query: String): List<FontFamily> {{
        val needle = query.trim().lowercase(Locale.ROOT)
        if (needle.isEmpty()) return families
        return families.filter {{
            it.label.lowercase(Locale.ROOT).contains(needle) || it.id.contains(needle) || it.category.label.lowercase(Locale.ROOT).contains(needle)
        }}
    }}

    /**
     * Loads a family face from the bundle. A missing or corrupt asset must never break drawing,
     * so the fallback is the platform's default face rather than an exception.
     */
    fun typeface(context: Context, id: String?): Typeface {{
        if (id == SYSTEM_ID) return Typeface.create("sans-serif", Typeface.NORMAL)
        val path = assetPath(id) ?: return Typeface.DEFAULT
        return try {{
            Typeface.createFromAsset(context.assets, path)
        }} catch (_: Exception) {{
            Typeface.DEFAULT
        }}
    }}
}}
'''


def asset_name(name: str) -> str:
    stem, bracket, _rest = name.partition("[")
    if not bracket:
        return name
    return f"{stem}-Variable{Path(name).suffix}"


def choose_face(items):
    rules = (
        lambda n: n.lower().endswith("-regular.ttf"),
        lambda n: "[" in n and "italic" not in n.lower(),
        lambda n: "[" in n,
        lambda n: "italic" not in n.lower(),
        lambda n: True,
    )
    for rule in rules:
        for item in items:
            if rule(item["file"]):
                return item
    raise AssertionError(items)


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__)
        return 2
    inventory, target, commit = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
    parse = SourceFileLoader("import_fonts", str(Path(__file__).with_name("import-fonts.py"))).load_module().parse
    families = defaultdict(list)
    files = 0
    for family, category, family_dir, file_name, license_name, _upstream in parse(inventory):
        files += 1
        families[(category, family_dir, family)].append(
            {"file": file_name, "name": asset_name(file_name), "license": license_name}
        )
    entries = []
    for (category, family_dir, family), items in families.items():
        face = choose_face(items)
        entries.append(
            (CATEGORY_ORDER.index(category), family.lower(), family_dir, family, category, face, len(items))
        )
    entries.sort()
    lines = []
    for _order, _label, family_dir, family, category, face, count in entries:
        asset_path = f"fonts/{category}/{family_dir}/{face['name']}"
        license_enum = "OFL" if face["license"] == "OFL" else "APACHE"
        lines.append(
            f'        FontFamily("{family_dir}", {escape(family)}, FontCategory.{category.upper()}, '
            f'"{asset_path}", FontLicense.{license_enum}, {count}),'
        )
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(HEADER.format(families=len(entries), files=files, commit=commit, rows="\n".join(lines)))
    print(f"Wrote {target} with {len(entries)} families / {files} files")
    return 0


def escape(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


if __name__ == "__main__":
    raise SystemExit(main())
