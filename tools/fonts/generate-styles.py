#!/usr/bin/env python3
"""Regenerate the bundled face list from the checked-in font assets.

Run from the repository root after importing fonts. The family catalog owns the
representative paths and licenses; this list only provides the selectable files.
"""
from pathlib import Path

root = Path('app/src/main/assets/fonts')
output = Path('app/src/main/java/dev/wallpep/fonts/BundledFontFiles.kt')
entries = []
for folder in sorted(p for p in root.glob('*/*') if p.is_dir()):
    files = sorted(p.name for p in folder.glob('*.ttf'))
    if files:
        values = ', '.join('"' + name + '"' for name in files)
        entries.append(f'    "{folder.name}" to listOf({values}),')
output.write_text('''package dev.wallpep.fonts

// Generated by tools/fonts/generate-styles.py from the checked-in font assets.
internal val bundledFontFiles: Map<String, List<String>> = mapOf(
''' + '\n'.join(entries) + '\n)\n')
